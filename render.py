BLANK = _FONT[" "]


def glyph(ch):
    return _FONT.get(ch, BLANK)


def text_width(s, scale):
    return len(s) * 6 * scale - scale


def wrap_words(words, max_chars):
    lines = []
    cur = ""
    for w in words:
        if not cur:
            cur = w
        elif len(cur) + 1 + len(w) <= max_chars:
            cur += " " + w
        else:
            lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def wrap_text(s, max_chars):
    out = []
    for part in s.split("\n"):
        out.extend(wrap_words(part.split(" "), max_chars))
    return out


# -------------------------------------------------------------- canvas ----
class Canvas:
    def __init__(self, w, h, bg):
        self.w = w
        self.h = h
        self.buf = bytearray(bg * (w * h))

    def px(self, x, y, color):
        if 0 <= x < self.w and 0 <= y < self.h:
            i = (y * self.w + x) * 3
            self.buf[i:i + 3] = color

    def rect(self, x, y, w, h, color):
        x0 = max(0, x)
        y0 = max(0, y)
        x1 = min(self.w, x + w)
        y1 = min(self.h, y + h)
        for yy in range(y0, y1):
            base = (yy * self.w + x0) * 3
            for xx in range(x0, x1):
                self.buf[base:base + 3] = color
                base += 3

    def hline(self, x, y, w, color, thick=1):
        self.rect(x, y, w, thick, color)

    def vline(self, x, y, h, color, thick=1):
        self.rect(x, y, thick, h, color)

    def line(self, x0, y0, x1, y1, color):
        dx = abs(x1 - x0)
        dy = -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            self.px(x0, y0, color)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def circle(self, cx, cy, r, color):
        for yy in range(cy - r, cy + r + 1):
            for xx in range(cx - r, cx + r + 1):
                if (xx - cx) ** 2 + (yy - cy) ** 2 <= r * r:
                    self.px(xx, yy, color)

    def ring(self, cx, cy, r, color, thick=2):
        for yy in range(cy - r, cy + r + 1):
            for xx in range(cx - r, cx + r + 1):
                d = (xx - cx) ** 2 + (yy - cy) ** 2
                if (r - thick) ** 2 <= d <= r * r:
                    self.px(xx, yy, color)

    def disc_outline(self, cx, cy, r, color):
        self.ring(cx, cy, r, color, 1)

    def text(self, x, y, s, scale, color, bold=False):
        cx = x
        for ch in s:
            g = glyph(ch)
            for row in range(7):
                bits = g[row]
                for col in range(5):
                    if bits[col] == "#":
                        bx = cx + col * scale
                        by = y + row * scale
                        self.rect(bx, by, scale, scale, color)
                        if bold:
                            self.rect(bx + 1, by, scale, scale, color)
            cx += 6 * scale
        return cx

    def text_center(self, y, s, scale, color, bold=False, cx=None):
        if cx is None:
            cx = self.w // 2
        w = text_width(s, scale)
        return self.text(cx - w // 2, y, s, scale, color, bold)

    def text_right(self, x, y, s, scale, color, bold=False):
        w = text_width(s, scale)
        return self.text(x - w, y, s, scale, color, bold)

    def para(self, x, y, s, scale, color, max_chars, lh=None, bold=False):
        if lh is None:
            lh = 8 * scale
        lines = wrap_text(s, max_chars)
        for ln in lines:
            self.text(x, y, ln, scale, color, bold)
            y += lh
        return y


# ------------------------------------------------------------- png out ----
def save_png(canvas, path):
    w, h = canvas.w, canvas.h
    raw = bytearray()
    stride = w * 3
    for yy in range(h):
        raw.append(0)
        raw += canvas.buf[yy * stride:(yy + 1) * stride]
    comp = zlib.compress(bytes(raw), 9)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        c += struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        return c

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", ihdr)
    png += chunk(b"IDAT", comp)
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)
    return len(png)
